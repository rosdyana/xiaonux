#!/usr/bin/env python3
"""Stage a bootable VM for the browser into dist/vm (Phase 1 format).

Copies the WASM build, firmware and kernel, writes a TinyEMU .cfg and splits
the root filesystem into TinyEMU HTTP block-device files (blk.txt +
blkNNNNNNNNN.bin). All-zero blocks are hard links to one file, so a sparse
2 GB image doesn't cost 2 GB of disk here (they still download if read).

Usage: stage-vm.py --bios B --kernel K --rootfs R [--cmdline ...] [--ram MB] [--out DIR]
"""
import argparse, json, os, shutil, sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ap = argparse.ArgumentParser()
ap.add_argument("--bios", required=True)
ap.add_argument("--kernel", required=True)
ap.add_argument("--rootfs", required=True)
ap.add_argument("--cmdline", default="console=hvc0 root=/dev/vda rw earlycon=sbi")
ap.add_argument("--ram", type=int, default=512)
ap.add_argument("--block-kb", type=int, default=256)
ap.add_argument("--wasm-dir", default=os.path.join(REPO, "build/wasm"))
ap.add_argument("--out", default=os.path.join(REPO, "dist/vm"))
a = ap.parse_args()

out = a.out
disk = os.path.join(out, "disk")
shutil.rmtree(out, ignore_errors=True)
os.makedirs(disk)

for f in ("xemu.mjs", "xemu.wasm"):
    shutil.copy2(os.path.join(a.wasm_dir, f), out)
shutil.copy2(a.bios, os.path.join(out, "bios.bin"))
shutil.copy2(a.kernel, os.path.join(out, "kernel.bin"))

bs = a.block_kb * 1024
zero = bytes(bs)
zero_path = os.path.join(disk, "zero.blk")
with open(zero_path, "wb") as z:
    z.write(zero)
n = nonzero = 0
with open(a.rootfs, "rb") as f:
    while True:
        buf = f.read(bs)
        if not buf:
            break
        if len(buf) < bs:
            buf += bytes(bs - len(buf))
        name = os.path.join(disk, f"blk{n:09d}.bin")
        if buf == zero:
            os.link(zero_path, name)
        else:
            with open(name, "wb") as o:
                o.write(buf)
            nonzero += 1
        n += 1
os.unlink(zero_path)
with open(os.path.join(disk, "blk.txt"), "w") as f:
    json.dump({"block_size": a.block_kb, "n_block": n}, f)

cfg = f"""/* xiaonux VM (generated by image/stage-vm.py) */
{{
    version: 1,
    machine: "riscv64",
    memory_size: {a.ram},
    bios: "bios.bin",
    kernel: "kernel.bin",
    cmdline: "{a.cmdline}",
    drive0: {{ file: "disk/blk.txt" }},
}}
"""
with open(os.path.join(out, "xiaonux.cfg"), "w") as f:
    f.write(cfg)
print(json.dumps({"out": out, "blocks": n, "nonzero_blocks": nonzero,
                  "nonzero_mb": round(nonzero * bs / 2**20, 1)}))
